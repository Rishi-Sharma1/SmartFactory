// 28-day sample attendance history helper
const generateAttendanceDays = (pattern: 'good' | 'late' | 'irregular' | 'leave'): WorkerAttendanceDay[] => {
  const days: WorkerAttendanceDay[] = [];
  for (let i = 1; i <= 28; i++) {
    const isWeekend = i % 7 === 6 || i % 7 === 0;
    let status: WorkerAttendanceDay['status'] = 'PRESENT';

    if (isWeekend) {
      status = 'WEEKEND';
    } else if (pattern === 'late' && (i === 4 || i === 11 || i === 18 || i === 25)) {
      status = 'LATE';
    } else if (pattern === 'irregular' && (i === 3 || i === 16)) {
      status = 'ABSENT';
    } else if (pattern === 'leave' && i >= 14 && i <= 20) {
      status = 'ON_LEAVE';
    }

    days.push({
      date: `2026-09-${i.toString().padStart(2, '0')}`,
      dayOfMonth: i,
      status,
    });
  }
  return days;
};

